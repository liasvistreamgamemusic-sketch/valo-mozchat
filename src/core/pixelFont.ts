export function hasGlyph(ch: string): boolean {
  return Object.prototype.hasOwnProperty.call(FONT, ch);
}

/**
 * Render a string with the bundled 5x7 font into a Bitmap.
 * spacing controls horizontal gap (in pixels) between characters.
 * scale multiplies both axes; useful for "chunky" output.
 * Returns null if the string contains any character without a glyph.
 */
export function renderTextBitmap(
  text: string,
  options: { spacing?: number; scale?: number } = {}
): Bitmap | null {
  const spacing = options.spacing ?? 1;
  const scale = options.scale ?? 1;
  for (const ch of text) {
    if (!hasGlyph(ch)) return null;
  }
  const cols = text.length;
  if (cols === 0) return createBitmap(0, 0);
  const w = cols * GLYPH_W * scale + (cols - 1) * spacing;
  const h = GLYPH_H * scale;
  const out = createBitmap(w, h);
  let cursor = 0;
  for (const ch of text) {
    const glyph = FONT[ch];
    for (let r = 0; r < GLYPH_H; r++) {
      const row = glyph[r];
      for (let c = 0; c < GLYPH_W; c++) {
        const on = (row >> (GLYPH_W - 1 - c)) & 1;
        if (!on) continue;
        // Paint a scale×scale block
        const px = cursor + c * scale;
        const py = r * scale;
        for (let dy = 0; dy < scale; dy++) {
          for (let dx = 0; dx < scale; dx++) {
            out.data[(py + dy) * w + (px + dx)] = 4;
          }
        }
      }
    }
    cursor += GLYPH_W * scale + spacing;
  }
  return out;
}
